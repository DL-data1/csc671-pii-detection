"""Build docs/experiments.md from the run summaries in docs/results/*.json (issue #8).

One row per run, plus mean +/- std rows for configs run with several seeds.
All scores are validation, document-level, entity-level (seqeval micro F1).

Usage:
    python scripts/experiment_table.py
"""

import json
import statistics
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS = REPO_ROOT / "docs" / "results"
OUT = REPO_ROOT / "docs" / "experiments.md"
TYPES = ["NAME_STUDENT", "STREET_ADDRESS", "PHONE_NUM", "EMAIL", "URL_PERSONAL", "USERNAME"]
SHORT = {"NAME_STUDENT": "NAME", "STREET_ADDRESS": "ADDR", "PHONE_NUM": "PHONE", "EMAIL": "EMAIL",
         "URL_PERSONAL": "URL", "USERNAME": "USER"}


def config_of(info):
    a = info["args"]
    cw = a.get("class_weights", "none")
    if cw != "none":
        cw = f"{cw} (cap {a.get('weight_cap')})"
    return {
        "model": info["base_model"].replace("distilbert-base-", ""),
        "lr": a["lr"],
        "epochs": a["epochs"],
        "batch": a["batch_size"],
        "warmup": a.get("warmup", 0.1),
        "class weights": cw,
        "window": f"{info.get('max_length', 512)}/{info.get('stride', 128)}",
    }


def row_scores(info):
    v, t = info["best_val"], info["best_val_per_type"]
    return [v["precision"], v["recall"], v["f1"], v["macro_f1"]] + [t[x]["f1-score"] for x in TYPES]


def best_epoch(info):
    epochs = info.get("per_epoch_val") or []
    if not epochs:
        return ""
    return f"{max(epochs, key=lambda e: e['eval_f1'])['epoch']:g}"


def fmt(x):
    return f"{x:.3f}"


def main():
    runs, held = [], []
    for p in sorted(RESULTS.glob("*.json")):
        info = json.loads(p.read_text())
        if "best_val" not in info:  # threshold sweeps etc.
            continue
        (held if info.get("holdout") else runs).append(info)
    runs.sort(key=lambda i: (not i["run_name"].startswith(("full_baseline", "base_")), i["run_name"]))

    cfg_cols = ["model", "lr", "epochs", "batch", "warmup", "class weights", "window"]
    score_cols = ["P", "R", "F1", "macro F1"] + [SHORT[t] for t in TYPES]
    head = ["run", *cfg_cols, "seed", "best ep", *score_cols, "time (s)"]
    lines = [
        "# Experiment table (issue #8)",
        "",
        "Generated by `python scripts/experiment_table.py` from `docs/results/*.json`. "
        "All scores are on the **validation** split: document-level, entity-level seqeval, best epoch of each run. "
        "Per-type columns are F1. Test was not used for any of these choices.",
        "",
        "## All runs",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "---|" * len(head),
    ]
    groups = {}
    for info in runs:
        cfg = config_of(info)
        key = json.dumps(cfg, sort_keys=True)
        groups.setdefault(key, (cfg, []))[1].append(info)
        s = row_scores(info)
        lines.append(
            "| " + " | ".join(
                [info["run_name"], *[str(cfg[c]) for c in cfg_cols], str(info["args"]["seed"]),
                 best_epoch(info), *[fmt(x) for x in s], str(info["runtime_sec"])]
            ) + " |"
        )

    multi = [(cfg, infos) for cfg, infos in groups.values() if len(infos) > 1]
    if multi:
        head2 = ["config", "runs", "seeds", *score_cols]
        lines += ["", "## Seed averages (mean ± std)", "", "| " + " | ".join(head2) + " |", "|" + "---|" * len(head2)]
        for cfg, infos in multi:
            cols = list(zip(*[row_scores(i) for i in infos]))
            cells = [f"{statistics.mean(c):.3f} ± {statistics.stdev(c):.3f}" for c in cols]
            desc = ", ".join(f"{k} {v}" for k, v in cfg.items())
            lines.append(
                "| " + " | ".join([desc, ", ".join(i["run_name"] for i in infos),
                                   ", ".join(str(i["args"]["seed"]) for i in infos), *cells]) + " |"
            )
    if held:
        head3 = ["run", "model", "epochs", "held-out style", "docs", "val F1 (other styles)",
                 "held-out P", "held-out R", "held-out F1"] + [f"held-out {SHORT[t]}" for t in TYPES]
        lines += [
            "",
            "## Unseen prompt style (generalization check)",
            "",
            "Prompt templates come in 4 styles with 2 variants each (0/4, 1/5, 2/6, 3/7). These runs drop one "
            "whole style from train and validation, pick the best epoch on the remaining validation docs, then "
            "score that checkpoint once on the dropped style's train+val documents. Test is not used. "
            "Trained on ~16% less data, so not comparable row-for-row with the table above.",
            "",
            "| " + " | ".join(head3) + " |",
            "|" + "---|" * len(head3),
        ]
        for info in sorted(held, key=lambda i: i["run_name"]):
            h, cfg = info["holdout"], config_of(info)
            lines.append("| " + " | ".join(
                [info["run_name"], cfg["model"], f"{cfg['epochs']:g}", "/".join(map(str, h["prompt_ids"])),
                 str(h["docs"]), fmt(info["best_val"]["f1"]), fmt(h["precision"]), fmt(h["recall"]), fmt(h["f1"])]
                + [fmt(h["per_type"].get(t, {}).get("f1-score", 0.0)) for t in TYPES]) + " |")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(runs)} runs, {len(held)} held-out runs)")


if __name__ == "__main__":
    main()
